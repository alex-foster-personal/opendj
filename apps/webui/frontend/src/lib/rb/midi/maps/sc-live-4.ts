/**
 * Denon DJ SC LIVE 4 practice-replica map: HINTS ONLY, no bindings (epic #9366, ADR-0137).
 *
 * Denon DJ publishes no MIDI message list for the SC LIVE 4 (its user guide carries none and the
 * Engine DJ community thread "Midi specification sc live 4" confirms none exists), and the clean-room
 * rule allows only public, official sources. So this map binds NOTHING: every wire below is a
 * PLACEHOLDER on channel 16 whose only job is to join a control in
 * tools/deck-diagrams/devices/sc-live-4/panel.json to its hint, so the practice replica renders every
 * control inert with the PARITY-TODO tooltip (house rule: no fake behavior). No wire here is a claim
 * about what the hardware sends.
 *
 * NOT in DEVICE_MAP_REGISTRY, on purpose: a map with placeholder wires must never be matched to a
 * real port, where its hints would mislabel the learn log. It is registered only in
 * PRACTICE_DEVICE_MAPS (practice-devices.ts). When an official list appears, replace the table with
 * transcribed wires, add bindings, and only then register it for hardware.
 *
 * Control names and callout numbers follow the official user guide v4.2.0 RevB, pages 23 to 26
 * (docs/controller/research/SC-LIVE-4-User-Guide.md). The table is generated by
 * tools/deck-diagrams/scripts/build_sc_live_4_panel.py --print-ts-hints; the unit test
 * tests/unit/practice-replica-sc-live-4.test.mjs resolves every panel control against it.
 */

