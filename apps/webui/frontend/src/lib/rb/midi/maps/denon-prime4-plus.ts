/**
 * Denon DJ PRIME 4+ practice-replica map: HINTS ONLY, no bindings (epic #9366, ADR-0137).
 *
 * Denon DJ publishes no MIDI message list for the PRIME 4+ (denondj.com/downloads checked
 * Sun 8 Nov 2026: the MIDI documents there are for the LC6000, MCX8000, MC6000 Mk2 and legacy
 * players). The clean-room rule forbids inventing wire numbers, so this map binds NOTHING and
 * lights NOTHING. Every top-panel control is a hint with a PLACEHOLDER wire on channel 16,
 * which exists only so the practice layout (tools/deck-diagrams/devices/denon-prime4-plus/
 * panel.json, built by tools/deck-diagrams/scripts/build_denon_prime4_plus_panel.py) joins to
 * this table and renders inert with the PARITY-TODO title. The placeholders are sequential in
 * layout order: notes for buttons and pads, CCs for knobs, faders, encoders and the platters.
 *
 * NOT IN DEVICE_MAP_REGISTRY, by design: nothing here may meet real MIDI traffic. A hardware
 * map for this unit needs a published list (or a probe-rig capture) that replaces every wire
 * below; until then do not register this map and do not add bindings to it.
 *
 * Sources: docs/controller/research/DENON-PRIME-4-PLUS-sources.md.
 */

import type { ControlHint, DeviceMap, DeviceMapEntry } from '$lib/rb/midi/midi-types';

/** Placeholder channel: no PRIME 4+ wire is documented, see the module comment. */
export const DENON_PRIME4_PLUS_PLACEHOLDER_CH = 16;

function hint(kind: 'note' | 'cc', id: number, label: string): ControlHint {
	return { source: { ch: DENON_PRIME4_PLUS_PLACEHOLDER_CH, kind, id }, label };
}

