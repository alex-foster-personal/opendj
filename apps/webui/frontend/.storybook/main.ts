import type { StorybookConfig } from '@storybook/sveltekit';

/**
 * Storybook is two things in this frontend:
 *
 * 1. The visual decision record: every pattern-setting UI rule gets a
 *    reference story plus an MDX decision doc in src/stories/ui-decisions/.
 * 2. The UI sandbox and contract suite: components render here exactly as in
 *    the app (same CSS, same components) but fed by fixtures instead of the
 *    daemon, engine and IPC, so agents can iterate on behavior in seconds.
 *    A story's `play` function is the saved contract; `pnpm test:contracts`
 *    runs every story in real Chromium via addon-vitest.
 *
 * Fixtures come from props first, then recorded daemon responses replayed by
 * MSW (src/sandbox/recorded.ts). See (private path).
 */
const config: StorybookConfig = {
	stories: ['../src/**/*.mdx', '../src/**/*.stories.@(js|ts)'],
	addons: ['@storybook/addon-docs', '@storybook/addon-vitest'],
	framework: '@storybook/sveltekit',
	// mockServiceWorker.js for msw-storybook-addon (generated by `msw init`).
	staticDirs: ['./msw'],
	// React twins (.storybook-react, `pnpm storybook:react` on 6007) appear
	// in this sidebar under "React twins" while both dev servers run.
	refs: (_config, { configType }) =>
		configType === 'DEVELOPMENT'
			? { react: { title: 'React twins', url: process.env.REACT_STORYBOOK_URL ?? 'http://localhost:6007' } }
			: {}
};

export default config;
