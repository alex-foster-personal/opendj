"""Isolation for linked-worktree node_modules entries (OPS-9171).

  - [if] a new add has a node_modules link [then] hook unlinks it, target stays, [else stop].
  - [if] frontend-deps runs [then] pnpm installs into a real directory, [else stop].
  - [if] sibling A is removed [then] B's esbuild still runs, [else stop].
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from scripts import sparse_worktree as sw
from tests.scripts.sparse_worktree_fixtures import add_worktree, build_primary

pytestmark = pytest.mark.requirement("OPS-9171")

NULL = "0" * 40


def test_isolate_unlinks_cross_worktree_link_without_touching_target(tmp_path: Path) -> None:
    """[if] worktree B's node_modules links into A [then] isolate unlinks it, [else stop]."""
    source = tmp_path / "A" / "apps" / "webui" / "frontend" / "node_modules"
    linked = tmp_path / "B" / "apps" / "webui" / "frontend" / "node_modules"
    source.mkdir(parents=True)
    marker = source / "marker"
    marker.write_text("keep\n", encoding="utf-8")
    linked.parent.mkdir(parents=True)
    linked.symlink_to(source, target_is_directory=True)

    assert linked.samefile(source)
    assert sw.isolate_node_modules(tmp_path / "B") == ["apps/webui/frontend/node_modules"]
    assert not linked.exists()
    assert marker.read_text(encoding="utf-8") == "keep\n"


def test_isolate_leaves_real_frontend_directory_alone(tmp_path: Path) -> None:
    """[if] node_modules is a real directory [then] isolate leaves its files, [else stop]."""
    modules = tmp_path / "apps" / "webui" / "frontend" / "node_modules"
    modules.mkdir(parents=True)
    marker = modules / "marker"
    marker.write_text("keep\n", encoding="utf-8")

    assert sw.isolate_node_modules(tmp_path) == []
    assert marker.read_text(encoding="utf-8") == "keep\n"


def test_isolate_unlinks_dangling_frontend_link(tmp_path: Path) -> None:
    """[if] a frontend node_modules link dangles [then] isolate unlinks it, [else stop]."""
    linked = tmp_path / "apps" / "webui" / "frontend" / "node_modules"
    linked.parent.mkdir(parents=True)
    linked.symlink_to(tmp_path / "removed-target", target_is_directory=True)

    assert linked.is_symlink()
    assert sw.isolate_node_modules(tmp_path) == ["apps/webui/frontend/node_modules"]
    assert not linked.is_symlink()


def test_isolate_unlinks_root_node_modules_link(tmp_path: Path) -> None:
    """[if] root node_modules links elsewhere [then] isolate unlinks it, [else stop]."""
    source = tmp_path / "source"
    source.mkdir()
    linked = tmp_path / "node_modules"
    linked.symlink_to(source, target_is_directory=True)

    assert sw.isolate_node_modules(tmp_path) == ["node_modules"]
    assert source.is_dir()


def test_post_checkout_isolates_a_planted_link(tmp_path: Path) -> None:
    """[if] a new worktree has a sibling link [then] the hook removes it, [else stop]."""
    primary = build_primary(tmp_path)
    worktree = tmp_path / "worktree"
    add_worktree(primary, worktree)
    fresh_modules = worktree / "apps" / "webui" / "frontend" / "node_modules"
    assert not fresh_modules.is_symlink()
    source = tmp_path / "source" / "node_modules"
    source.mkdir(parents=True)
    marker = source / "marker"
    marker.write_text("keep\n", encoding="utf-8")
    linked = worktree / "apps" / "webui" / "frontend" / "node_modules"
    linked.parent.mkdir(parents=True, exist_ok=True)
    linked.symlink_to(source, target_is_directory=True)

    assert sw.main(["--repo", str(worktree), "post-checkout", NULL, "x" * 40, "1"]) == 0
    assert not linked.is_symlink()
    assert marker.read_text(encoding="utf-8") == "keep\n"


def _pnpm_env(store: Path) -> dict[str, str]:
    return {**os.environ, "CI": "true", "pnpm_config_store_dir": str(store)}


def _run_pnpm(pnpm: str, cwd: Path, args: list[str], env: dict[str, str]) -> None:
    try:
        done = subprocess.run(
            [pnpm, *args],
            cwd=cwd,
            env=env,
            capture_output=True,
            text=True,
            check=False,
            timeout=180,
        )
    except subprocess.TimeoutExpired as exc:
        pytest.fail(f"UNAVAILABLE: pnpm timed out: {exc}")
    if done.returncode != 0:
        detail = done.stderr or done.stdout
        pytest.fail(f"UNAVAILABLE: pnpm failed (rc={done.returncode}): {detail}")


def test_removing_one_worktree_keeps_other_esbuild_working(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """[if] A and B install via the store [then] B's esbuild survives removing A, [else stop]."""
    pnpm = shutil.which("pnpm")
    if pnpm is None:
        pytest.fail("UNAVAILABLE: pnpm is not on PATH")

    primary = build_primary(tmp_path)
    frontend = primary / "apps" / "webui" / "frontend"
    frontend.mkdir(parents=True, exist_ok=True)
    (frontend / "package.json").write_text(
        json.dumps(
            {
                "name": "worktree-esbuild-fixture",
                "version": "1.0.0",
                "private": True,
                "packageManager": "pnpm@11.11.0",
                "devDependencies": {"esbuild": "0.25.0"},
            }
        )
        + "\n",
        encoding="utf-8",
    )
    (frontend / "pnpm-workspace.yaml").write_text(
        "allowBuilds:\n  esbuild: true\n", encoding="utf-8"
    )
    store = tmp_path / "pnpm-store"
    env = _pnpm_env(store)
    _run_pnpm(pnpm, frontend, ["install"], env)
    monkeypatch.setenv("pnpm_config_store_dir", str(store))
    subprocess.run(["git", "-C", str(primary), "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(primary), "commit", "-qm", "frontend fixture"], check=True)

    worktree_a = tmp_path / "worktree-a"
    worktree_b = tmp_path / "worktree-b"
    add_worktree(primary, worktree_a)
    add_worktree(primary, worktree_b)
    assert sw.install_frontend_deps(worktree_a) == 0
    assert sw.install_frontend_deps(worktree_b) == 0

    modules_a = worktree_a / "apps" / "webui" / "frontend" / "node_modules"
    modules_b = worktree_b / "apps" / "webui" / "frontend" / "node_modules"
    assert modules_a.is_dir() and not modules_a.is_symlink()
    assert modules_b.is_dir() and not modules_b.is_symlink()
    assert not modules_a.samefile(modules_b)

    subprocess.run(
        ["git", "-C", str(primary), "worktree", "remove", "--force", str(worktree_a)], check=True
    )
    done = subprocess.run(
        [pnpm, "exec", "esbuild", "--version"],
        cwd=worktree_b / "apps" / "webui" / "frontend",
        env=env,
        capture_output=True,
        text=True,
        check=False,
        timeout=30,
    )
    assert done.returncode == 0, done.stderr or done.stdout
    assert "0.25.0" in done.stdout
