#!/usr/bin/env python3
"""Export the Doppler secrets THIS repo references into a gitignored .env for cloud agents.

Mini-PRD:
  ✔︎ Select only Doppler names that appear in tracked repo text (never the whole config).
      [if] the config holds a personal secret no tracked file mentions [then ⛔️ it is written]
      [if] a referenced name is in Doppler [then ⛔️ it is missing from the output]
      [if] zero names match [then ⛔️ the script exits 0]
  ✔︎ Never print a secret value; print names only.
      [if] stdout or stderr contains any exported value [then ⛔️]
      [if] the output file is not mode 0600 [then ⛔️]
      [if] the output path is not gitignored [then ⛔️ the script writes it]
  ✔︎ Fail fast on Doppler errors (no cached fallback).
      [if] Doppler auth or access fails [then ⛔️ the script exits 0]

Prefer a scoped DOPPLER_TOKEN plus `doppler run` in cloud ((private path));
this file is for platforms that only accept a pasted .env.

Usage:
  python3 scripts/doppler_cloud_env.py [--project general] [--config dev_personal]
      [--out .env.cloud] [--dry-run]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
NAME_RE = re.compile(r"\b[A-Z][A-Z0-9_]{2,}\b")
EXCLUDED_NAMES = frozenset({"DOPPLER_PROJECT", "DOPPLER_CONFIG", "DOPPLER_ENVIRONMENT"})


# -----------------------------------------------------------------------------
def _fail(message: str) -> None:
    sys.exit(f"[ERROR] {message}")


def _doppler_secrets(project: str, config: str) -> dict[str, str]:
    result = subprocess.run(
        [
            "doppler",
            "secrets",
            "download",
            "--no-read-env",
            "--no-file",
            "--no-fallback",
            "--format",
            "json",
            "-p",
            project,
            "-c",
            config,
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        _fail(f"doppler download failed for {project}/{config}: {result.stderr.strip()[:300]}")
    return json.loads(result.stdout)


def _names_referenced_in_repo() -> set[str]:
    files = subprocess.run(["git", "ls-files", "-z"], capture_output=True, cwd=REPO_ROOT, check=True).stdout.split(
        b"\0"
    )
    names: set[str] = set()
    for rel in filter(None, files):
        path = REPO_ROOT / rel.decode()
        if not path.is_file() or path.stat().st_size > 2_000_000:
            continue
        names.update(NAME_RE.findall(path.read_text(errors="ignore")))
    return names


def _assert_gitignored(out: Path) -> None:
    ignored = subprocess.run(["git", "check-ignore", "-q", str(out)], cwd=REPO_ROOT, check=False)
    if ignored.returncode != 0:
        _fail(f"{out} is not gitignored; refusing to write secrets there")


def _env_line(name: str, value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'{name}="{escaped}"'


# -----------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", required=True)
    parser.add_argument("--config", required=True)
    parser.add_argument("--out", default=".env.cloud")
    parser.add_argument("--exclude", nargs="*", default=[], help="names to leave out")
    parser.add_argument("--dry-run", action="store_true", help="list names, write nothing")
    args = parser.parse_args()

    out = (REPO_ROOT / args.out).resolve()
    secrets = _doppler_secrets(args.project, args.config)
    selected = sorted((set(secrets) & _names_referenced_in_repo()) - EXCLUDED_NAMES - set(args.exclude))
    if not selected:
        _fail(f"no {args.project}/{args.config} names are referenced in this repo")

    print(f"[OK] {len(selected)} of {len(secrets)} names in {args.project}/{args.config} are referenced by this repo:")
    for name in selected:
        print(f"  {name}")
    if args.dry_run:
        print("[OK] dry run, nothing written")
        return

    _assert_gitignored(out)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(f"# generated by scripts/doppler_cloud_env.py from {args.project}/{args.config}\n")
        handle.write("\n".join(_env_line(n, secrets[n]) for n in selected) + "\n")
    os.chmod(out, 0o600)
    print(f"[OK] wrote {out.relative_to(REPO_ROOT)} (mode 600, gitignored)")


if __name__ == "__main__":
    main()
