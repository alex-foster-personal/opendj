"""Generate ``RESERVED_FIXED_PORTS`` in ``apps/webui/port_config.py`` from the suites.

Every fixed, compile-time port a Playwright / Vite / WDIO e2e or desktop suite
binds directly must be excluded from the dynamic worktree-port allocator
(issue #1613, INFRA-08). The set used to be hand-written, one line per suite,
so it conflicted on nearly every landing that added a suite (#8583). This
script derives it from the suite files themselves and rewrites the generated
block in place. A landing conflict in that block is resolved by rerunning it.

    uv run python -m scripts.gen_reserved_ports           # rewrite the block
    uv run python -m scripts.gen_reserved_ports --check   # exit 1 when stale

Requirements:
- ✔︎ ✅ 🎯 Rewrites the block in place, idempotently.
  - [if] the script runs twice [then] the second run changes nothing, [else stop]
- ✔︎ ✅ 🎯 One entry per line, sorted by port, each with the config file it came from.
  - [if] a port is pinned by several files [then] the comment names the first config and how many more, [else stop]
- ✔︎ ✅ 🎯 Ports no suite file declares live in EXTRA_PORTS, and an extra that is also discovered is an error.
  - [if] an extra is discoverable [then] generation raises naming it, [else stop]
- ✔︎ ✅ 🎯 --check exits 1 naming this command when the committed block differs.
  - [if] a config gains a pinned port [then] --check fails until the block is regenerated, [else stop]
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Mapping
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PORT_CONFIG = REPO / "apps" / "webui" / "port_config.py"
GENERATOR_COMMAND = "uv run python -m scripts.gen_reserved_ports"

#: (directory, the label its paths carry in a provenance comment).
SUITE_ROOTS: tuple[tuple[Path, str], ...] = (
    (REPO / "apps/webui/frontend/tests/e2e", "tests/e2e"),
    (REPO / "apps/desktop", "apps/desktop"),
)

#: A loopback port pinned as a literal. Same shape tests/scripts/
#: test_ci_e2e_fixed_port_steps_are_locked.py uses to find a suite's own port.
FIXED_PORT_LITERAL = re.compile(
    r"(?:PORT[A-Za-z_]*\s*=\s*|PORT[A-Za-z_]*\s*\?\?\s*|127\.0\.0\.1:|localhost:)(\d{4,5})\b"
)

#: Ports to reserve that no suite file declares, each with its provenance.
#: Empty today: PREFERRED_ENGINE_PORT 7700 is discovered from
#: apps/desktop/electron/src/engine.ts, which mirrors the Rust constant.
EXTRA_PORTS: Mapping[int, str] = {}

#: A suite configuration file (vite.x.config.ts, wdio.conf.ts), preferred as provenance.
CONFIG_FILE = re.compile(r"\.conf(?:ig)?\.ts$")

BLOCK_START = f"        # BEGIN generated by `{GENERATOR_COMMAND}`; rerun it, never hand-edit\n"
BLOCK_END = "        # END generated\n"


class StaleExtraError(ValueError):
    """An EXTRA_PORTS entry that a suite file also declares."""


# ----- discovery ---------------------------------------------------------


def discovered_fixed_ports(roots: tuple[Path, ...]) -> dict[int, set[str]]:
    """Every pinned-port literal under ``roots``, port -> paths relative to their root."""
    discovered: dict[int, set[str]] = {}
    for root in roots:
        for path in sorted(root.rglob("*.ts")):
            if "node_modules" in path.parts:
                continue
            text = path.read_text(encoding="utf-8", errors="ignore")
            for literal in FIXED_PORT_LITERAL.findall(text):
                discovered.setdefault(int(literal), set()).add(path.relative_to(root).as_posix())
    return discovered


def labelled_fixed_ports(suite_roots: tuple[tuple[Path, str], ...] = SUITE_ROOTS) -> dict[int, list[str]]:
    """Port -> every declaring file as ``<label>/<relative path>``, sorted."""
    labelled: dict[int, list[str]] = {}
    for root, label in suite_roots:
        for port, paths in discovered_fixed_ports((root,)).items():
            labelled.setdefault(port, []).extend(f"{label}/{rel}" for rel in paths)
    return {port: sorted(paths) for port, paths in labelled.items()}


# ----- rendering ---------------------------------------------------------


def _provenance(paths: list[str]) -> str:
    """The first config file (else the first file), plus how many others pin it."""
    configs = [p for p in paths if CONFIG_FILE.search(p)]
    first = (configs or paths)[0]
    others = len(paths) - 1
    return first if others == 0 else f"{first} (+{others} more)"


def render_block(labelled: Mapping[int, list[str]], extras: Mapping[int, str] = EXTRA_PORTS) -> str:
    """The generated block body, BEGIN and END marker lines included."""
    clash = sorted(set(extras) & set(labelled))
    if clash:
        raise StaleExtraError(f"EXTRA_PORTS {clash} are also declared by suite files; remove them from EXTRA_PORTS")
    entries = {port: _provenance(paths) for port, paths in labelled.items()}
    entries.update({port: f"{why} (extra)" for port, why in extras.items()})
    lines = "".join(f"        {port},  # {entries[port]}\n" for port in sorted(entries))
    return BLOCK_START + lines + BLOCK_END


def rewrite(source: str, block: str) -> str:
    """``source`` with its generated block replaced by ``block``."""
    start = source.find(BLOCK_START)
    end = source.find(BLOCK_END)
    if start < 0 or end < start:
        raise ValueError(f"{PORT_CONFIG.relative_to(REPO)} has no generated RESERVED_FIXED_PORTS block markers")
    return source[:start] + block + source[end + len(BLOCK_END) :]


def expected_source(source: str, suite_roots: tuple[tuple[Path, str], ...] = SUITE_ROOTS) -> str:
    return rewrite(source, render_block(labelled_fixed_ports(suite_roots)))


# ----- entry point -------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed block is stale; write nothing")
    args = parser.parse_args(argv)
    source = PORT_CONFIG.read_text(encoding="utf-8")
    expected = expected_source(source)
    if args.check:
        if expected != source:
            print(f"[ERROR] RESERVED_FIXED_PORTS is stale; run `{GENERATOR_COMMAND}`", file=sys.stderr)
            return 1
        print("[OK] RESERVED_FIXED_PORTS is current")
        return 0
    if expected == source:
        print("[OK] RESERVED_FIXED_PORTS already current; nothing written")
        return 0
    PORT_CONFIG.write_text(expected, encoding="utf-8")
    print(f"[OK] rewrote RESERVED_FIXED_PORTS in {PORT_CONFIG.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
