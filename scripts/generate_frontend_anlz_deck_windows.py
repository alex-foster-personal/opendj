"""Generate synthetic anlz-detail-window fixtures for frontend unit tests (issue #11396).

Builds every tri-band value and beat from a seeded synthetic model (kick, snare,
hat and pad envelopes over stepped section levels), never from an earlier capture
(issue #13446), writes manifests with sha256, and invokes the Node helper for the
derived artifacts (pre-B5 golden from the pinned pre-B5 commit, Settings sample).
"""

