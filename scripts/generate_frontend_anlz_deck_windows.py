def _sha256_bytes(data: bytes) -> str:
    """Return the hex sha256 of data."""
    return hashlib.sha256(data).digest().hex()


def _pwv(value: float) -> float:
    """Quantise a 0..1 level to a PWV byte (0..127) and back, 4 decimals."""
    return round(round(max(0.0, min(1.0, value)) * 127) / 127, 4)


def synthetic_window(spec: WindowSpec) -> dict[str, Any]:
    """Build one deterministic synthetic tri-band window and its beats from the spec alone."""
    rng = random.Random(spec.seed)
    n = spec.point_range[1] - spec.point_range[0]
    span_s = spec.window_s[1] - spec.window_s[0]
    period = 60.0 / spec.bpm
    section_s = span_s / len(spec.sections)
    low: list[float] = []
    mid: list[float] = []
    high: list[float] = []
    for i in range(n):
        t = i * span_s / n
        # Section edges sit 0.37 s off the beat grid, so they are not whole blocks.
        section = int(max(0.0, t - 0.37) / section_s)
        level = spec.sections[min(len(spec.sections) - 1, section)]
        beat_pos = t / period
        k = int(beat_pos)
        since = (beat_pos - k) * period
        kick = math.exp(-since / 0.06)
        # Syncopated snare on the "and" of odd beats: its rise is the window's
        # moderate change, clear of the beat lines (snap tests check both).
        and_s = since - period / 2
        attack = 0.6 + 0.4 * min(1.0, and_s / 0.025)  # a hit, then 25 ms swell
        snare = attack * math.exp(-and_s / 0.09) if k % 2 == 1 and and_s >= 0 else 0.0
        off = (beat_pos + 0.5) % 1.0 * period
        hat = math.exp(-off / 0.03)
        pad = 0.35 + 0.1 * math.sin(2 * math.pi * t / (4 * period))
        jitter = 0.04 * (rng.random() - 0.5)
        lo = level * (0.4 + spec.kick_weight * kick) + jitter
        mi = level * (0.6 * pad + 0.7 * snare) + jitter
        hi = level * (0.08 + 0.25 * hat) + 0.5 * jitter
        if spec.plateau is not None and 0 <= t - spec.plateau[0] < spec.plateau[1]:
            mi = spec.plateau[2] + jitter / 4
        if spec.crash_s is not None and t >= spec.crash_s:
            hi = max(hi, math.exp(-(t - spec.crash_s) / 0.02))
        low.append(_pwv(lo))
        mid.append(_pwv(mi))
        high.append(_pwv(hi))
    t0 = spec.window_s[0]
    beats: list[dict[str, Any]] = []
    for k in range(int(span_s / period) + 1):
        t = round(t0 + k * period, 3)
        if t >= spec.window_s[1]:
            break
        beats.append({"bpm": spec.bpm, "n": k % 4 + 1, "t": t} if spec.beat_keys else {"t": t})
    return {"detail": {"low": low, "mid": mid, "high": high}, "beats": beats}


def _apply_spec(path: Path, spec: WindowSpec) -> bytes:
    """Write the spec's synthetic window to path and return the bytes written."""
    window = synthetic_window(spec)
    payload = {
        "stable_id": spec.stable_id,
        "duration_ms": spec.duration_ms,
        "detail_length": spec.detail_length,
        "window_s": list(spec.window_s),
        "point_range": list(spec.point_range),
        "detail": window["detail"],
        "beats": window["beats"],
    }
    text = json.dumps(payload, separators=(",", ":"))
    path.write_text(text, encoding="utf-8")
    return text.encode("utf-8")


def _write_manifest(spec: WindowSpec, file_sha: dict[str, str]) -> None:
    manifest_path = FIX / spec.manifest_name
    files: dict[str, dict[str, Any]] = {}
    for name, digest in file_sha.items():
        files[name] = {"bytes": (FIX / name).stat().st_size, "sha256": digest}
    if "gothic-blocks-pre-b5-golden.json" in file_sha:
        files["gothic-blocks-pre-b5-golden.json"]["provenance"] = (
            "blockHeights of the synthetic gothic window at main ef76df4099 (pre-B5: p99 "
            "divisor, inputs clamped at 1, VARIANT_DEFAULT blend, NO_GRID_VARIANT kick), "
            "1200 px for 24 s; grid = window beats, noGrid = none. Captured by "
            "capture-gothic-golden.mjs from a detached ef76df4099 checkout, never from the "
            "code under test."
        )
    base: dict[str, Any] = {
        "schema_version": 1,
        "capture": {
            "kind": "anlz-detail-window",
            "source": "scripts/generate_frontend_anlz_deck_windows.py (synthetic, issue #11396)",
            "captured_on": "2026-11-11",
            "track_stable_id": spec.stable_id,
            "title": spec.title,
            "artist": spec.artist,
            "selection": spec.selection,
            "synthetic": True,
        },
        "files": files,
    }
    manifest_path.write_text(json.dumps(base, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    digests: dict[str, str] = {}
    for spec in (BLOCKS, GOTHIC):
        body = _apply_spec(FIX / spec.json_name, spec)
        digests[spec.json_name] = _sha256_bytes(body)

    if not NODE_DERIVED.is_file():
        print(f"missing helper: {NODE_DERIVED}", file=sys.stderr)
        return 1
    subprocess.run(
        ["node", str(NODE_DERIVED)],
        cwd=REPO,
        check=True,
    )
    golden = FIX / "gothic-blocks-pre-b5-golden.json"
    digests["gothic-blocks-pre-b5-golden.json"] = _sha256_bytes(golden.read_bytes())

    _write_manifest(BLOCKS, {BLOCKS.json_name: digests[BLOCKS.json_name]})
    _write_manifest(
        GOTHIC,
        {
            GOTHIC.json_name: digests[GOTHIC.json_name],
            "gothic-blocks-pre-b5-golden.json": digests["gothic-blocks-pre-b5-golden.json"],
        },
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
