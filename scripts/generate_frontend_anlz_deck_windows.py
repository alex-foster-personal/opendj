@dataclass(frozen=True)
class WindowSpec:
    json_name: str
    manifest_name: str
    stable_id: str
    duration_ms: int
    detail_length: int
    window_s: tuple[float, float]
    point_range: tuple[int, int]
    bpm: float
    title: str
    artist: str
    selection: str
    seed: int
    sections: tuple[float, ...]
    beat_keys: bool
    kick_weight: float = 0.15
    # (start_s, length_s, level): a held mid plateau, louder than the rest of the
    # body but under the crash, so a p99 divisor pins it at full height.
    plateau: tuple[float, float, float] | None = None
    # Window second of a one-point-wide high-band crash at full scale (the true peak).
    crash_s: float | None = None


