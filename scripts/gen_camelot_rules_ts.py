"""Write the browser's copy of the Camelot mixing rules from apps/shared/harmonic.py.

The compatible filter's rule checkboxes must mean the same thing in the
browser (camelot.ts, next-only-filter.ts) and on the server (ui-prefs
validation, harmonic.py). harmonic.CAMELOT_RULES is the one definition; this
script renders it as TypeScript, and tests/shared/test_camelot_rules.py fails
when the committed file differs from what this script would write.

Usage: uv run --no-sync python -m scripts.gen_camelot_rules_ts [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from apps.shared.harmonic import CAMELOT_RULES

TS_PATH = Path(__file__).resolve().parents[1] / "apps/webui/frontend/src/lib/player/key/camelot-rules.generated.ts"


def render_camelot_rules_ts() -> str:
    rules = [
        {
            "id": rule.id,
            "label": rule.label,
            "example": rule.example,
            "default_on": rule.default_on,
            "moves": [{"from": m.from_letter, "to": m.to_letter, "step": m.step} for m in rule.moves],
        }
        for rule in CAMELOT_RULES
    ]
    body = json.dumps(rules, indent="\t", ensure_ascii=False)
    ids = " | ".join(json.dumps(rule.id) for rule in CAMELOT_RULES)
    return (
        "// GENERATED by scripts/gen_camelot_rules_ts.py from apps/shared/harmonic.py CAMELOT_RULES.\n"
        "// Do not edit: change harmonic.py and re-run the script.\n"
        f"export type CamelotRuleId = {ids};\n\n"
        "export interface CamelotMove {\n"
        "\tfrom: 'A' | 'B' | '*';\n"
        "\tto: 'same' | 'other';\n"
        "\tstep: number;\n"
        "}\n\n"
        "export interface CamelotRule {\n"
        "\tid: CamelotRuleId;\n"
        "\tlabel: string;\n"
        "\texample: string;\n"
        "\tdefault_on: boolean;\n"
        "\tmoves: readonly CamelotMove[];\n"
        "}\n\n"
        f"export const CAMELOT_RULES: readonly CamelotRule[] = {body};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale")
    args = parser.parse_args(argv)
    rendered = render_camelot_rules_ts()
    if args.check:
        if TS_PATH.read_text(encoding="utf-8") != rendered:
            print(f"[ERROR] {TS_PATH} is stale; run python -m scripts.gen_camelot_rules_ts", file=sys.stderr)
            return 1
        print("[OK] camelot rules TS matches harmonic.py")
        return 0
    TS_PATH.write_text(rendered, encoding="utf-8")
    print(f"[OK] wrote {TS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
