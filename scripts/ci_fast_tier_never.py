"""Build `ci/fast-tier-never.txt` from the JUnit reports of fast-tier legs.

SMARTEST-CI round 30 ((private path), Wed 4 Nov 2026). The fast tier selects tests the
durations ledger recorded under 0.5 s, and the ledger is measured in the FULL lane. There a
shared cost (an `lru_cache` over the repository tree, a module fixture) is paid by a slow
sibling the fast tier deselects, so inside a leg the same cost lands on a sibling the ledger
recorded at a few milliseconds. Only a leg's own JUnit shows it. This module reads those
reports and names every test module whose over-ceiling tests (each at or over the tier's
0.5 s ceiling) took at least `--min-seconds` together in a majority of the legs that ran
it; `scripts/pytest_fast_tier.py` moves those modules to the slow tier.
They still run in the sharded lane when the PR selects them and in the nightly full lane.

Requirements (mini-PRD)
- [if] a module's over-ceiling tests sum to at least --min-seconds in more than half of the
  legs that ran any of its tests [then] it is listed, [else stop] ✔︎ ✅ 🎯
- [if] a module has many tests that are each under the ceiling [then] their sum never lists
  it, however large: only over-ceiling tests count, [else stop] ✔︎ ✅ 🎯
- [if] a module reaches --min-seconds in half of its legs or fewer [then] it is not listed,
  [else stop] ✔︎ ✅ 🎯
- [if] no JUnit report is given, or one has no testcase with a `file` attribute [then] exit
  non-zero naming the file, never an empty list, [else stop] ✔︎ ✅ 🎯

Usage: python -m scripts.ci_fast_tier_never --ceiling 0.5 --min-seconds 2 --out ci/fast-tier-never.txt
junit-fast-*.xml (leg JUnit from the `fast-tier-leg-N` R2 artifacts, `scripts/r2_artifact.py`).
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

import defusedxml.ElementTree as ET  # type: ignore[import-untyped]

HEADER: str = """\
# Test modules moved out of the fast tier (scripts/pytest_fast_tier.py, --fast-tier-never).
# One test file path (every test in it) or one node id per line. Generated by
# scripts/ci_fast_tier_never.py from fast-tier leg JUnit: in a majority of the {legs} legs
# read, each module below had tests at or over the {ceiling:g} s ceiling that took at least
# {min_seconds:g} s together, although the durations ledger records them under it (the cost
# of a deselected slow sibling lands on them). They still run in the sharded lane and the
# nightly full lane, and an always-fast entry still wins. Every entry must match a collected
# test, or the fast tier refuses to run. SMARTEST-CI round 30, (private path).
# Regenerate rather than hand-edit.
"""


class JUnitError(ValueError):
    pass


@dataclass(frozen=True)
class Leg:
    source: str
    seconds_by_module: dict[str, float]


def read_leg(path: Path, ceiling: float) -> Leg:
    """Seconds spent per module in tests at or over the ceiling (0.0 for a module with none)."""
    seconds: defaultdict[str, float] = defaultdict(float)
    for case in ET.parse(path).getroot().iter("testcase"):
        module = case.get("file")
        if module:
            took = float(case.get("time") or 0)
            seconds[module] += took if took >= ceiling else 0.0
    if not seconds:
        raise JUnitError(f"{path}: no testcase carries a `file` attribute (junit_family=xunit1?)")
    return Leg(source=str(path), seconds_by_module=dict(seconds))


def modules_over(legs: list[Leg], min_seconds: float) -> list[str]:
    ran: Counter[str] = Counter()
    over: Counter[str] = Counter()
    for leg in legs:
        for module, seconds in leg.seconds_by_module.items():
            ran[module] += 1
            over[module] += seconds >= min_seconds
    return sorted(module for module, count in ran.items() if over[module] * 2 > count)


def render(modules: list[str], min_seconds: float, ceiling: float, legs: int) -> str:
    return HEADER.format(min_seconds=min_seconds, ceiling=ceiling, legs=legs) + "".join(f"{m}\n" for m in modules)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("junit", nargs="+", type=Path)
    parser.add_argument("--min-seconds", type=float, required=True)
    parser.add_argument("--ceiling", type=float, required=True, help="the leg's --fast-tier-max-seconds")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    legs = [read_leg(path, args.ceiling) for path in args.junit]
    modules = modules_over(legs, args.min_seconds)
    args.out.write_text(render(modules, args.min_seconds, args.ceiling, len(legs)), encoding="utf-8")
    print(f"[fast-tier-never] {len(modules)} modules from {len(legs)} legs -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
